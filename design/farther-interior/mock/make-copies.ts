// Issue #950 round: writes the region pipeline copies river arm B draws through, from the engine's own files at this sha, by a short list of exact replacements, each asserted to land once (the method of `make-copies.ts` in `design/shape-and-count/mock/`). Everything a replacement does not touch is the engine verbatim, and selfcheck.ts proves the copies draw today's close-up byte for byte with no hook given.
//   region-copy.ts : generateRegionWorld as generateRegionWorldWith(world, spec, hooks): an after-chain carve, the chain's carve, and the water stage
//   chain-copy.ts  : buildChainedField, carving each level it builds when its spec carries a carve, the carve joining the cache key
// Run from the tree root: node out/950/mock/make-copies.ts
import { readFileSync, writeFileSync } from "node:fs";

const TREE = new URL("../../../", import.meta.url).pathname;
const HERE = new URL("./", import.meta.url).pathname;
const SHA = "cbf57b8f";

function replaceOnce(text: string, from: string, to: string, file: string): string {
  const at = text.indexOf(from);
  if (at < 0 || text.indexOf(from, at + 1) >= 0) throw new Error(`${file}: expected exactly one ${JSON.stringify(from.slice(0, 70))}`);
  return text.slice(0, at) + to + text.slice(at + from.length);
}

function rewriteImports(text: string, fromDir: string): string {
  return text
    .replace(/from "\.\.\/([^"]+)"/g, (_m, p: string) => `from "../../../src/${p}"`)
    .replace(/from "\.\/([^"]+)"/g, (_m, p: string) => `from "../../../src/${fromDir}/${p}"`);
}

const HEAD = (file: string): string => `// GENERATED by out/950/mock/make-copies.ts from ${file} at ${SHA}; do not edit, re-run the script.\n`;

{
  const file = "src/world/detail-chain.ts";
  let t = rewriteImports(readFileSync(`${TREE}${file}`, "utf8"), "world");
  t = replaceOnce(t, `import { FULL_WINDOW, LOD_BANDS, lodWindowFor, quantizeCenter } from "../../../src/world/lod.ts";`, `import { FULL_WINDOW, LOD_BANDS, lodWindowFor, quantizeCenter } from "../../../src/world/lod.ts";\nimport type { ChainCarve } from "./hooks.ts";`, file);
  t = replaceOnce(t, `  readonly coastWarp?: number;\n};`, `  readonly coastWarp?: number;\n  readonly carve?: ChainCarve;\n};`, file);
  t = replaceOnce(t, `    spec.coastWarp ?? "-",\n  ].join("|");`, `    spec.coastWarp ?? "-",\n    ...(spec.carve ? [spec.carve.key] : []),\n  ].join("|");`, file);
  t = replaceOnce(t, `  cache.set(key, out);\n  return out;\n}`, `  const carved = spec.carve ? spec.carve.fn(out, spec.window) : out;\n  cache.set(key, carved);\n  return carved;\n}`, file);
  writeFileSync(`${HERE}chain-copy.ts`, HEAD(file) + t);
}

{
  const file = "src/world/region.ts";
  let t = rewriteImports(readFileSync(`${TREE}${file}`, "utf8"), "world");
  t = replaceOnce(t, `import { buildChainedField, detailForWindow, type ChainCache } from "../../../src/world/detail-chain.ts";`, `import { buildChainedField, detailForWindow, type ChainCache } from "./chain-copy.ts";\nimport type { RegionHooks } from "./hooks.ts";`, file);
  t = replaceOnce(t, `function regionElevation(g: RegionGrid, spec: RegionSpec, seaLevel: number): Field {`, `function regionElevation(g: RegionGrid, spec: RegionSpec, seaLevel: number, hooks: RegionHooks): Field {`, file);
  t = replaceOnce(t, `          worldAspect,\n          seaLevel,\n        },\n        spec.chainCache,`, `          worldAspect,\n          seaLevel,\n          ...(hooks.chainCarve ? { carve: hooks.chainCarve } : {}),\n        },\n        spec.chainCache,`, file);
  t = replaceOnce(t, `  elevSpan: number,\n): { flow: FlowResult; rivers: River[]; riverCells: Uint8Array } {`, `  elevSpan: number,\n  hooks: RegionHooks,\n): { flow: FlowResult; rivers: River[]; riverCells: Uint8Array } {`, file);
  t = replaceOnce(
    t,
    `  const flow = computeFlow(elev, seaLevel, rain);\n  const rivers = anchorRegionRivers(world, window, gridW, gridH, elev, flow, seaLevel);`,
    `  const waters = hooks.waters ? hooks.waters({ world, window, gridW, gridH, elev, seaLevel, rain }) : null;\n  const flow = waters ? waters.flow : computeFlow(elev, seaLevel, rain);\n  const rivers = waters ? waters.rivers : anchorRegionRivers(world, window, gridW, gridH, elev, flow, seaLevel);`,
    file,
  );
  t = replaceOnce(t, `export function generateRegionWorld(world: World, spec: RegionSpec): World {`, `export function generateRegionWorldWith(world: World, spec: RegionSpec, hooks: RegionHooks): World {`, file);
  t = replaceOnce(t, `  const elev = regionElevation(g, spec, seaLevel);`, `  const chained = regionElevation(g, spec, seaLevel, hooks);\n  const elev = hooks.carve ? hooks.carve(chained, window) : chained;`, file);
  t = replaceOnce(t, `  const { flow, rivers, riverCells } = regionWaters(g, elev, seaLevel, elevSpan);`, `  const { flow, rivers, riverCells } = regionWaters(g, elev, seaLevel, elevSpan, hooks);`, file);
  writeFileSync(`${HERE}region-copy.ts`, HEAD(file) + t);
}
