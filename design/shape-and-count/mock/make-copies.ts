// Issue #849 spike: writes the pipeline copies the round draws through, from the engine's own files at this sha, by a
// short list of exact replacements, each asserted to land once. Everything a replacement does not touch is the
// engine verbatim, so a still differs from today's only where its terrain inputs differ.
//   generate-copy.ts : generateWorld, its terrain stage taking the spike's inputs
//   region-copy.ts   : generateRegionWorld, BOTH arms taking the spike's inputs (the coast warp and the edge included,
//                      which is the pass-through Sub 1, Issue #850, builds; today's region.ts drops the warp)
//   chain-copy.ts    : buildChainedField, its bare build taking the spike's inputs, the cache key carrying them
// Run from the tree: node out/844/mock/make-copies.ts
import { readFileSync, writeFileSync } from "node:fs";

const TREE = new URL("../../../", import.meta.url).pathname;
const HERE = new URL("./", import.meta.url).pathname;

function replaceOnce(text: string, from: string, to: string, file: string): string {
  const at = text.indexOf(from);
  if (at < 0 || text.indexOf(from, at + 1) >= 0) throw new Error(`${file}: expected exactly one ${JSON.stringify(from.slice(0, 60))}`);
  return text.slice(0, at) + to + text.slice(at + from.length);
}

function rewriteImports(text: string, fromDir: string): string {
  return text
    .replace(/from "\.\.\/([^"]+)"/g, (_m, p: string) => `from "../../../src/${p}"`)
    .replace(/from "\.\/([^"]+)"/g, (_m, p: string) => `from "../../../src/${fromDir}/${p}"`);
}

const HEAD = (file: string): string => `// GENERATED by out/844/mock/make-copies.ts from ${file} at 581a6de3; do not edit, re-run the script.\n`;

{
  const file = "src/world/generate.ts";
  let t = rewriteImports(readFileSync(`${TREE}${file}`, "utf8"), "world");
  t = replaceOnce(t, `import { buildHeightfield, type MapType } from "../../../src/terrain/heightfield.ts";`, `import type { MapType } from "../../../src/terrain/heightfield.ts";\nimport { spikeHeightfield, type TerrainInputs } from "./terrain.ts";`, file);
  t = replaceOnce(t, `function terrainStage(recipe: WorldRecipe, rng: Rng): { elev: Field; seaLevel: number; winds: Winds } {`, `function terrainStage(recipe: WorldRecipe, rng: Rng, inputs: TerrainInputs): { elev: Field; seaLevel: number; winds: Winds } {`, file);
  t = replaceOnce(
    t,
    `  const elev = buildHeightfield({
    seed,
    gridW,
    gridH,
    mapType,
    ...(recipe.coastWarp !== undefined ? { coastWarp: recipe.coastWarp } : {}),
  });`,
    `  if (inputs.seed !== seed || inputs.mapType !== mapType || inputs.coastWarp !== recipe.coastWarp) throw new Error("terrain inputs disagree with the recipe");
  const elev = spikeHeightfield(inputs, { gridW, gridH });`,
    file,
  );
  t = replaceOnce(t, `export function generateWorld(recipe: WorldRecipe): World {`, `export function generateWorldWith(recipe: WorldRecipe, inputs: TerrainInputs): World {`, file);
  t = replaceOnce(t, `  const { elev, seaLevel, winds } = terrainStage(recipe, rng);`, `  const { elev, seaLevel, winds } = terrainStage(recipe, rng, inputs);`, file);
  writeFileSync(`${HERE}generate-copy.ts`, HEAD(file) + t);
}

