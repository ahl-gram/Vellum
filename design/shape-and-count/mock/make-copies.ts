  const file = "src/world/region.ts";
  let t = rewriteImports(readFileSync(`${TREE}${file}`, "utf8"), "world");
  t = replaceOnce(t, `import { buildHeightfield, type UvWindow } from "../../../src/terrain/heightfield.ts";`, `import type { UvWindow } from "../../../src/terrain/heightfield.ts";\nimport { spikeHeightfield, type TerrainInputs } from "./terrain.ts";`, file);
